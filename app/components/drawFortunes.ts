export function shuffledFortunes(): string[] {
  const fortunes: string[] = [...DRAW_FORTUNES];
  for (let i = fortunes.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [fortunes[i], fortunes[j]] = [fortunes[j], fortunes[i]];
  }
  return fortunes;
}
